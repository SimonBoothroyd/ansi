/// The commit payload — PURE DART (invariant 2). Built client-side after the
/// user resolves every reconciliation line; handed to the import repository
/// which writes it through PowerSync.
///
/// **Every line has exactly one identity** (migration 0017's
/// `line_item_identity_xor`): either an existing `ingredientId` — a row the
/// vocabulary already holds, including one the review just created through
/// the New-ingredient sheet and the flesh-out form (plan 0025 D3) — or a
/// `subRecipeId`, the household recipe a review-linked line points at (step
/// 8.6 / D1 · D6). The commit creates no ingredient of its own: the
/// `import_stub` leg that minted a coalesced row per unmatched name retired
/// with D3, so no line can arrive here without a real id.
///
/// Step refs are still by **line index** here (`steps`); the repository assigns
/// `line_item_id`s in the flattened line order and remaps the refs on write
/// (§4.6). Line ids are generated by the data layer (uuids + timestamps live
/// there).
library;

import 'package:freezed_annotation/freezed_annotation.dart';

import '../../../core/units/units.dart';
import 'reconciliation_payload.dart';

part 'commit_payload.freezed.dart';

/// A resolved line. Exactly one identity is set: [ingredientId] or
/// [subRecipeId].
@freezed
abstract class CommitLine with _$CommitLine {
  const factory CommitLine({
    /// The flattened line index — its position in the commit's line order and
    /// the value step tokens ref before the remap.
    required int lineIndex,
    String? ingredientId,

    /// The household recipe this line was LINKED to at review (8.6 / D6). When
    /// it is set the line is a COMPONENT line and [ingredientId] is null; the
    /// repository writes no `measure_id` for it either (measures are an
    /// ingredient concept, and migration 0017 pins both rules).
    String? subRecipeId,
    double? quantity,
    String? unit,
    String? note,

    /// The recipe says this line may be left out (plan 0025 / D6b) — seeded
    /// from the extractor's raw flag, toggled at review, written to
    /// `recipe_line_item.optional`. Always false on a component line: an
    /// optional sub-recipe is a week-level question, not a line fact.
    @Default(false) bool optional,
  }) = _CommitLine;
}

@freezed
abstract class CommitGroup with _$CommitGroup {
  const factory CommitGroup({
    String? name,
    @Default(<CommitLine>[]) List<CommitLine> lines,
  }) = _CommitGroup;
}

/// A user correction to write back as an alias (`source='import_correction'`,
/// lane B's learning loop): the raw [aliasText] now points at [ingredientId].
@freezed
abstract class CommitCorrection with _$CommitCorrection {
  const factory CommitCorrection({
    required String ingredientId,
    required String aliasText,
  }) = _CommitCorrection;
}

@freezed
abstract class CommitPayload with _$CommitPayload {
  const factory CommitPayload({
    required String title,
    required double servingsBase,
    String? servingsRaw,

    /// What one batch MAKES, as the review's header states it (8.6 / D2 ·
    /// D9, board frame h) — prefilled from `yield_raw` only when that was a
    /// plain amount + unit, and otherwise whatever the human typed, or
    /// nothing. Both halves or neither: a half-stated yield is half a fact.
    /// The SECOND denomination is the editor's affordance, now at review too
    /// (plan 0025 #4): the same header form, so the same two slots.
    double? yieldQty,
    Unit? yieldUnit,
    double? yieldQty2,
    Unit? yieldUnit2,
    int? cookTimeSeconds,
    int? totalTimeSeconds,

    /// Shelf life, as the header's SHELF LIFE section states it — unset
    /// unless a human set it, because no page prints it.
    int? keepsForDays,
    @Default(false) bool freezable,
    int? freezerDays,

    /// Where the recipe is FILED. Null files into the household's default
    /// book at write, exactly where commit has always put an import; the
    /// review's draft names that book from the start so FILE UNDER can move
    /// it before it lands.
    String? bookId,
    String? sectionId,
    @Default(<CommitGroup>[]) List<CommitGroup> groups,
    @Default(<Step>[]) List<Step> steps,
    @Default(<CommitCorrection>[]) List<CommitCorrection> corrections,
  }) = _CommitPayload;
}
